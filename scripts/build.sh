#!/bin/bash

target_release() {
    cd release
    cmake -DCMAKE_BUILD_TYPE=Release ../..
    make
    echo "Built target in build/release/"
    cd ../..
}

target_debug() {
    cd debug 
    cmake -DCMAKE_BUILD_TYPE=Debug ../..
    make
    echo "Built target in build/debug/"
    cd ../..
}

# Create folder for distribution
if [ "$1" = "release" ]
then
    if [ -d "$tessellation" ]
    then
        rm -rf -d tessellation
    fi

    mkdir -p tessellation
fi

# Creates the folder for the buildaries
mkdir -p tessellation 
mkdir -p tessellation/assets
mkdir -p build
mkdir -p build/release
mkdir -p build/debug
cd build

# Builds target
if [ "$1" = "release" ]
then
    target_release
    cp build/release/tessellation tessellation/tessellation
else
    target_debug
fi

cp -R assets tessellation/
